-- 1. App Settings
CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- 2. Subjects
CREATE TABLE IF NOT EXISTS subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT DEFAULT '',
    color TEXT DEFAULT '#2563eb',
    is_archived BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Chapters
CREATE TABLE IF NOT EXISTS chapters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT DEFAULT '',
    order_index INT DEFAULT 0,
    status TEXT DEFAULT 'Not Started',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(subject_id, name)
);

-- 4. Topics
CREATE TABLE IF NOT EXISTS topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id BIGINT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(chapter_id, name)
);

-- 5. Notes
CREATE TABLE IF NOT EXISTS notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
    chapter_id BIGINT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
    topic_id BIGINT REFERENCES topics(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    source_type TEXT DEFAULT 'pasted',
    raw_content TEXT NOT NULL,
    extracted_content TEXT NOT NULL,
    extraction_status TEXT DEFAULT 'processed',
    extraction_notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Flashcards (SM-2 Spaced Repetition)
CREATE TABLE IF NOT EXISTS flashcards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
    chapter_id BIGINT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
    topic_id BIGINT REFERENCES topics(id) ON DELETE SET NULL,
    note_id BIGINT REFERENCES notes(id) ON DELETE SET NULL,
    card_type TEXT DEFAULT 'concept',
    question TEXT NOT NULL,
    answer TEXT NOT NULL,
    source_reference TEXT DEFAULT '',
    context_snippet TEXT DEFAULT '',
    status TEXT DEFAULT 'approved',
    ease_factor REAL DEFAULT 2.5,
    repetitions INT DEFAULT 0,
    interval_days INT DEFAULT 0,
    due_date DATE DEFAULT CURRENT_DATE,
    last_reviewed_at TIMESTAMPTZ,
    last_rating INT,
    consecutive_correct INT DEFAULT 0,
    total_reviews INT DEFAULT 0,
    lapses INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Flashcard Review Log
CREATE TABLE IF NOT EXISTS flashcard_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flashcard_id BIGINT NOT NULL REFERENCES flashcards(id) ON DELETE CASCADE,
    rating INT NOT NULL,
    ease_factor_before REAL NOT NULL,
    ease_factor_after REAL NOT NULL,
    interval_before INT NOT NULL,
    interval_after INT NOT NULL,
    review_time_ms INT DEFAULT 0,
    reviewed_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Practice Questions (MCQs)
CREATE TABLE IF NOT EXISTS practice_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
    chapter_id BIGINT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
    topic_id BIGINT REFERENCES topics(id) ON DELETE SET NULL,
    note_id BIGINT REFERENCES notes(id) ON DELETE SET NULL,
    question_text TEXT NOT NULL,
    question_type TEXT DEFAULT 'mcq',
    options_json JSONB DEFAULT '[]'::jsonb,
    correct_answer TEXT NOT NULL,
    explanation TEXT DEFAULT '',
    source_reference TEXT DEFAULT '',
    topic_name TEXT DEFAULT '',
    difficulty TEXT DEFAULT 'Medium',
    is_pyq BOOLEAN DEFAULT FALSE,
    pyq_exam TEXT DEFAULT '',
    pyq_year TEXT DEFAULT '',
    verification_status TEXT DEFAULT 'user_practice',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Test Attempts
CREATE TABLE IF NOT EXISTS test_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    test_mode TEXT DEFAULT 'practice',
    subject_id BIGINT REFERENCES subjects(id) ON DELETE SET NULL,
    chapter_id BIGINT REFERENCES chapters(id) ON DELETE SET NULL,
    question_count INT NOT NULL,
    time_limit_minutes INT DEFAULT 30,
    time_taken_seconds INT DEFAULT 0,
    score REAL DEFAULT 0,
    max_score REAL DEFAULT 0,
    correct_count INT DEFAULT 0,
    incorrect_count INT DEFAULT 0,
    unanswered_count INT DEFAULT 0,
    accuracy REAL DEFAULT 0,
    status TEXT DEFAULT 'in_progress',
    started_at TIMESTAMPTZ DEFAULT NOW(),
    completed_at TIMESTAMPTZ
);

-- 10. Test Responses
CREATE TABLE IF NOT EXISTS test_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES test_attempts(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES practice_questions(id) ON DELETE CASCADE,
    user_answer TEXT,
    is_correct INT DEFAULT 0,
    is_marked_for_review INT DEFAULT 0,
    time_spent_seconds INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. Mistake Notebook
CREATE TABLE IF NOT EXISTS mistakes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES practice_questions(id) ON DELETE CASCADE,
    attempt_id BIGINT REFERENCES test_attempts(id) ON DELETE SET NULL,
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
    chapter_id BIGINT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
    topic_name TEXT DEFAULT '',
    user_selected_answer TEXT NOT NULL,
    correct_answer TEXT NOT NULL,
    explanation TEXT DEFAULT '',
    source_reference TEXT DEFAULT '',
    error_type TEXT DEFAULT 'Unclassified',
    user_reflection TEXT DEFAULT '',
    repeated_count INT DEFAULT 1,
    status TEXT DEFAULT 'unresolved',
    last_reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. PYQs (Previous Year Questions)
CREATE TABLE IF NOT EXISTS pyqs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_name TEXT NOT NULL,
    exam_year TEXT NOT NULL,
    tier TEXT DEFAULT 'Tier 1',
    shift TEXT DEFAULT '',
    subject_id BIGINT REFERENCES subjects(id) ON DELETE SET NULL,
    chapter_id BIGINT REFERENCES chapters(id) ON DELETE SET NULL,
    topic_name TEXT DEFAULT '',
    question_text TEXT NOT NULL,
    options_json JSONB DEFAULT '[]'::jsonb,
    correct_answer TEXT NOT NULL,
    explanation TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =============================================================================
-- INDEXES FOR MAXIMUM QUERY PERFORMANCE
-- =============================================================================
CREATE INDEX IF NOT EXISTS idx_chapters_subject_id ON chapters(subject_id);
CREATE INDEX IF NOT EXISTS idx_notes_chapter_id ON notes(chapter_id);
CREATE INDEX IF NOT EXISTS idx_flashcards_chapter_id ON flashcards(chapter_id);
CREATE INDEX IF NOT EXISTS idx_flashcards_due_date ON flashcards(due_date);
CREATE INDEX IF NOT EXISTS idx_practice_questions_chapter_id ON practice_questions(chapter_id);
CREATE INDEX IF NOT EXISTS idx_mistakes_chapter_id ON mistakes(chapter_id);
CREATE INDEX IF NOT EXISTS idx_test_responses_attempt_id ON test_responses(attempt_id);

-- =============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- Enable Row Level Security and allow full access for anon and authenticated users
-- =============================================================================
DO $$
DECLARE
    tbl text;
    tables text[] := ARRAY[
        'settings', 'subjects', 'chapters', 'topics', 'notes',
        'flashcards', 'flashcard_reviews', 'practice_questions',
        'test_attempts', 'test_responses', 'mistakes', 'pyqs'
    ];
BEGIN
    FOREACH tbl IN ARRAY tables LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY;', tbl);
        EXECUTE format('DROP POLICY IF EXISTS "Public access policy" ON %I;', tbl);
        EXECUTE format('CREATE POLICY "Public access policy" ON %I FOR ALL TO public USING (true) WITH CHECK (true);', tbl);
    END LOOP;
END $$;

