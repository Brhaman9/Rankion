async function handleNoteUploadSubmit(event) {
  event.preventDefault();
  const sb = getSupabase();
  if (!sb) return showToast('Supabase not connected', 'danger');

  const subject_id = parseInt(document.getElementById('upload-subject-select').value);
  const chapter_id = parseInt(document.getElementById('upload-chapter-select').value);
  const title = document.getElementById('upload-note-title').value.trim();
  const fileInput = document.getElementById('upload-file-input');

  if (!fileInput.files || fileInput.files.length === 0) {
    showToast('Please select a file.', 'danger');
    return;
  }

  const file = fileInput.files[0];
  const reader = new FileReader();

  reader.onload = async (e) => {
    const content = e.target.result;
    try {
      const { error } = await sb.from('notes').insert([{
        subject_id,
        chapter_id,
        title,
        source_type: file.name.endsWith('.pdf') ? 'pdf' : 'txt',
        raw_content: content,
        extracted_content: content,
        extraction_status: 'processed',
        extraction_notes: `Uploaded file: ${file.name}`
      }]);
      if (error) throw error;
      showToast('Document uploaded and saved to notes.', 'success');
      closeModal('modal-note-upload');
      await loadNotesList();
    } catch (err) {
      showToast('Failed to save document: ' + err.message, 'danger');
    }
  };

  reader.onerror = () => {
    showToast('Error reading file from disk.', 'danger');
  };

  reader.readAsText(file);
}

