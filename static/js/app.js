// SM-2 Calculation Function
function calculateSM2(rating, repetitions, intervalDays, easeFactor) {
  const qMap = { 1: 1, 2: 3, 3: 4, 4: 5 };
  const q = qMap[rating] || 3;
  let newEf = easeFactor + (0.1 - (5 - q) * (0.08 + (5 - q) * 0.02));
  if (newEf < 1.3) newEf = 1.3;
  newEf = Math.round(newEf * 100) / 100;

  let newReps = 0;
  let newInterval = 1;
  let lapse = false;

  if (rating === 1) {
    newReps = 0;
    newInterval = 1;
    lapse = true;
  } else if (rating === 2) {
    newReps = repetitions + 1;
    if (intervalDays <= 1) newInterval = 1;
    else if (intervalDays <= 3) newInterval = 2;
    else newInterval = Math.max(1, Math.floor(intervalDays * 1.2));
  } else if (rating === 3) {
    newReps = repetitions + 1;
    if (newReps === 1) newInterval = 1;
    else if (newReps === 2) newInterval = 6;
    else newInterval = Math.max(Math.floor(intervalDays * newEf), intervalDays + 1);
  } else {
    newReps = repetitions + 1;
    if (newReps === 1) newInterval = 2;
    else if (newReps === 2) newInterval = 8;
    else newInterval = Math.max(Math.floor(intervalDays * newEf * 1.35), intervalDays + 2);
  }

  const nextDate = new Date();
  nextDate.setDate(nextDate.getDate() + newInterval);
  const dueDate = nextDate.toISOString().split('T')[0];

  return {
    repetitions: newReps,
    interval_days: newInterval,
    ease_factor: newEf,
    due_date: dueDate,
    lapse: lapse,
    last_reviewed_at: new Date().toISOString()
  };
}

