let sbClient = null;

function getSupabase() {
  if (sbClient) return sbClient;
  const url = window.RANKION_CONFIG?.SUPABASE_URL || localStorage.getItem('rankion_supabase_url') || '';
  const key = window.RANKION_CONFIG?.SUPABASE_ANON_KEY || localStorage.getItem('rankion_supabase_anon_key') || '';
  
  if (url && key && window.supabase) {
    try {
      sbClient = window.supabase.createClient(url.trim(), key.trim());
      return sbClient;
    } catch (e) {
      console.error('Supabase initialization error:', e);
    }
  }
  return null;
}

async function checkSupabaseConnection(silent = false) {
  const client = getSupabase();
  const dot = document.getElementById('sb-status-dot');
  const text = document.getElementById('sb-status-text');
  const badge = document.getElementById('settings-sb-badge');
  const msg = document.getElementById('setting-sb-status-msg');

  if (!client) {
    if (dot) dot.style.background = '#ef4444';
    if (text) text.textContent = 'Connect Supabase';
    if (badge) { badge.className = 'badge badge-red'; badge.textContent = 'Not Connected'; }
    if (!silent) showToast('Please connect your Supabase database in Settings.', 'warning');
    return false;
  }

  try {
    const { data, error } = await client.from('settings').select('key').limit(1);
    if (error && error.code !== 'PGRST116') {
      throw error;
    }
    if (dot) dot.style.background = '#10b981';
    if (text) text.textContent = 'Supabase Cloud';
    if (badge) { badge.className = 'badge badge-green'; badge.textContent = 'Connected & Active'; }
    if (msg) { msg.style.color = 'var(--accent-primary)'; msg.textContent = 'Connected to Supabase PostgreSQL database.'; }
    return true;
  } catch (err) {
    if (dot) dot.style.background = '#ef4444';
    if (text) text.textContent = 'Supabase Error';
    if (badge) { badge.className = 'badge badge-red'; badge.textContent = 'Connection Error'; }
    if (msg) { msg.style.color = '#ef4444'; msg.textContent = 'Error: ' + (err.message || 'Check credentials or run SQL migration script.'); }
    if (!silent) showToast('Database connection failed. Please verify credentials or run the SQL migration.', 'danger');
    return false;
  }
}

