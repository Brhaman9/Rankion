async function handleUnlockSubmit(event) {
  event.preventDefault();
  const input = document.getElementById('passcode-input');
  const errorEl = document.getElementById('lock-error-msg');
  const passcode = input.value.trim();
  errorEl.textContent = '';

  let correctCode = '2486';
  const sb = getSupabase();
  if (sb) {
    try {
      const { data } = await sb.from('settings').select('value').eq('key', 'passcode').maybeSingle();
      if (data && data.value) correctCode = data.value;
    } catch (e) {}
  } else {
    const cached = localStorage.getItem('rankion_passcode');
    if (cached) correctCode = cached;
  }

  if (passcode === correctCode) {
    showAppShell();
  } else {
    errorEl.textContent = 'Access denied. Incorrect passcode.';
    input.value = '';
    input.focus();
  }
}

