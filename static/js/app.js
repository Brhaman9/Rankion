async function handleSaveSupabaseConfig(event) {
  event.preventDefault();
  let url = document.getElementById('sb-input-url')?.value.trim() || document.getElementById('setting-sb-url')?.value.trim() || '';
  let key = document.getElementById('sb-input-key')?.value.trim() || document.getElementById('setting-sb-key')?.value.trim() || '';

  if (!url || !key) {
    showToast('Please provide both Supabase Project URL and Anon Key.', 'danger');
    return;
  }

  // Normalize URL
  if (!url.startsWith('http://') && !url.startsWith('https://')) {
    url = 'https://' + url;
  }
  url = url.replace(/\/+$/, '');

  localStorage.setItem('rankion_supabase_url', url);
  localStorage.setItem('rankion_supabase_anon_key', key);
  
  window.RANKION_CONFIG = window.RANKION_CONFIG || {};
  window.RANKION_CONFIG.SUPABASE_URL = url;
  window.RANKION_CONFIG.SUPABASE_ANON_KEY = key;

  // Re-init client
  sbClient = null;
  const connected = await checkSupabaseConnection(true);

  if (connected) {
    showToast('Successfully connected to Supabase database!', 'success');
    closeModal('modal-supabase-config');
    await loadInitialData();
  } else {
    showToast('Saved credentials, but table test failed. Make sure you ran the SQL schema script!', 'warning');
  }
}

async function testSupabaseConnection() {
  const inUrl = document.getElementById('sb-input-url')?.value.trim() || document.getElementById('setting-sb-url')?.value.trim();
  const inKey = document.getElementById('sb-input-key')?.value.trim() || document.getElementById('setting-sb-key')?.value.trim();
  const stat = document.getElementById('sb-test-status') || document.getElementById('setting-sb-status-msg');

  if (!inUrl || !inKey) {
    if (stat) { stat.style.color = '#ef4444'; stat.textContent = 'Please enter URL and Anon Key first.'; }
    return;
  }

  if (stat) { stat.style.color = 'var(--text-muted)'; stat.textContent = 'Testing connection...'; }

  try {
    let url = inUrl.replace(/\/+$/, '');
    if (!url.startsWith('http')) url = 'https://' + url;
    const testClient = window.supabase.createClient(url, inKey);
    const { data, error } = await testClient.from('settings').select('key').limit(1);
    if (error && error.code !== 'PGRST116') throw error;
    
    if (stat) {
      stat.style.color = 'var(--accent-primary)';
      stat.textContent = '✓ Connection verified! Supabase is accessible.';
    }
    showToast('Supabase connection verified!', 'success');
  } catch (err) {
    if (stat) {
      stat.style.color = '#ef4444';
      stat.textContent = '✗ Connection failed: ' + (err.message || 'Check URL/Key or run the SQL schema script.');
    }
    showToast('Connection failed: ' + (err.message || 'Check credentials'), 'danger');
  }
}

