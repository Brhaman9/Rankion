async function handleRestoreBackup(event) {
  const file = event.target.files[0];
  if (!file) return;

  const sb = getSupabase();
  if (!sb) return showToast('Supabase not connected', 'danger');

  const reader = new FileReader();
  reader.onload = async (e) => {
    try {
      const data = JSON.parse(e.target.result);
      if (data.subjects && data.subjects.length > 0) {
        await sb.from('subjects').upsert(data.subjects);
      }
      if (data.chapters && data.chapters.length > 0) {
        await sb.from('chapters').upsert(data.chapters);
      }
      if (data.flashcards && data.flashcards.length > 0) {
        await sb.from('flashcards').upsert(data.flashcards);
      }
      if (data.practice_questions && data.practice_questions.length > 0) {
        await sb.from('practice_questions').upsert(data.practice_questions);
      }
      if (data.notes && data.notes.length > 0) {
        await sb.from('notes').upsert(data.notes);
      }
      showToast('Database restore complete!', 'success');
      await loadInitialData();
    } catch (err) {
      showToast('Failed to restore backup: ' + err.message, 'danger');
    }
  };
  reader.readAsText(file);
}

