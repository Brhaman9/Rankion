async function handleStartTest(event) {
  event.preventDefault();
  const sb = getSupabase();
  if (!sb) return showToast('Supabase not connected', 'danger');

  const subject_id = parseInt(document.getElementById('test-subject-select').value) || null;
  const chapter_id = parseInt(document.getElementById('test-chapter-select').value) || null;
  const num_questions = parseInt(document.getElementById('test-question-count')?.value) || 20;
  const time_limit = Math.max(10, Math.round(num_questions * 1.2));

  try {
    let query = sb.from('practice_questions').select('*');
    if (chapter_id) query = query.eq('chapter_id', chapter_id);
    else if (subject_id) query = query.eq('subject_id', subject_id);

    const { data: allQs, error } = await query;
    if (error) throw error;

    if (!allQs || allQs.length === 0) {
      showToast('No practice questions found for this selection. Please add questions first!', 'warning');
      return;
    }

    // Shuffle and slice
    const shuffled = [...allQs].sort(() => 0.5 - Math.random());
    const selected = shuffled.slice(0, num_questions);

    let testTitle = 'SSC Practice Test';
    if (chapter_id) {
      const ch = chaptersCache.find(x => x.id === chapter_id);
      if (ch) testTitle = `${ch.name} Practice Test`;
    }

    // Insert test attempt
    const { data: attempt, error: aErr } = await sb.from('test_attempts').insert([{
      title: testTitle,
      test_mode: 'practice',
      subject_id,
      chapter_id,
      question_count: selected.length,
      time_limit_minutes: time_limit,
      max_score: selected.length * 2,
      status: 'in_progress'
    }]).select().single();

    if (aErr) throw aErr;

    closeModal('modal-test-config');

    // Launch CBT Simulator
    launchExamSimulator({
      attempt_id: attempt.id,
      title: testTitle,
      time_limit_minutes: time_limit,
      questions: selected.map(q => ({
        id: q.id,
        question_text: q.question_text,
        options: typeof q.options_json === 'string' ? JSON.parse(q.options_json) : (q.options_json || []),
        correct_answer: q.correct_answer,
        explanation: q.explanation || '',
        subject_id: q.subject_id,
        chapter_id: q.chapter_id
      }))
    });

  } catch (e) {
    showToast('Failed to start test: ' + e.message, 'danger');
  }
}

function launchExamSimulator(testData) {
  currentExamAttempt = testData;
  currentExamQuestions = testData.questions.map(q => ({
    ...q,
    user_answer: null,
    is_marked: false,
    time_spent: 0
  }));
  currentExamQuestionIndex = 0;
  examTimeElapsedSeconds = 0;

  document.getElementById('exam-sim-title').textContent = testData.title;
  startExamTimer();
  renderExamQuestion();
  renderExamPalette();

  openModal('modal-exam-simulator');
}

function startExamTimer() {
  if (examTimerInterval) clearInterval(examTimerInterval);
  const totalSeconds = (currentExamAttempt.time_limit_minutes || 30) * 60;
  
  const timerEl = document.getElementById('exam-timer-display');

  examTimerInterval = setInterval(() => {
    examTimeElapsedSeconds++;
    const remaining = Math.max(0, totalSeconds - examTimeElapsedSeconds);
    const m = Math.floor(remaining / 60);
    const s = remaining % 60;
    if (timerEl) {
      timerEl.textContent = `${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
      if (remaining <= 300) timerEl.style.color = '#ef4444';
      else timerEl.style.color = 'var(--text-main)';
    }

    if (remaining <= 0) {
      clearInterval(examTimerInterval);
      showToast('Time is up! Submitting your test...', 'warning');
      finalizeTestSubmission();
    }
  }, 1000);
}

