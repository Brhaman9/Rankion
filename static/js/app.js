async function loadInitialData() {
  await fetchSubjectsCache();
  await refreshGlobalBadges();
}

async function fetchSubjectsCache() {
  const sb = getSupabase();
  if (!sb) return;
  try {
    const { data, error } = await sb.from('subjects').select('*').order('id', { ascending: true });
    if (!error && data) {
      subjectsCache = data;
      const badge = document.getElementById('badge-subject-count');
      if (badge) badge.textContent = subjectsCache.length;
    }
  } catch (e) {
    subjectsCache = [];
  }
}

async function refreshGlobalBadges() {
  const sb = getSupabase();
  if (!sb) return;
  try {
    const today = new Date().toISOString().split('T')[0];
    const { count: dueCount } = await sb.from('flashcards').select('*', { count: 'exact', head: true }).lte('due_date', today);
    const badgeDue = document.getElementById('badge-due-flashcards');
    if (badgeDue) {
      if (dueCount > 0) {
        badgeDue.textContent = `${dueCount} Due`;
        badgeDue.style.display = 'inline-block';
      } else {
        badgeDue.style.display = 'none';
      }
    }

    const { count: mistakeCount } = await sb.from('mistakes').select('*', { count: 'exact', head: true }).neq('status', 'mastered');
    const badgeMistake = document.getElementById('badge-mistake-count');
    if (badgeMistake) badgeMistake.textContent = mistakeCount || 0;
  } catch (e) {}
}

