async function submitCardRating(rating) {
  const sb = getSupabase();
  const card = studyQueue[currentStudyIndex];
  if (!card || !sb) return;

  const sm2 = calculateSM2(rating, card.repetitions || 0, card.interval_days || 0, card.ease_factor || 2.5);

  if (sm2.lapse) studySessionStats.lapses++;
  else studySessionStats.correct++;

  const timeSpentMs = Date.now() - cardStartTime;

  try {
    // Update card
    await sb.from('flashcards').update({
      ease_factor: sm2.ease_factor,
      repetitions: sm2.repetitions,
      interval_days: sm2.interval_days,
      due_date: sm2.due_date,
      last_reviewed_at: sm2.last_reviewed_at,
      last_rating: rating,
      total_reviews: (card.total_reviews || 0) + 1,
      lapses: sm2.lapse ? (card.lapses || 0) + 1 : (card.lapses || 0),
      consecutive_correct: sm2.lapse ? 0 : (card.consecutive_correct || 0) + 1,
      updated_at: new Date().toISOString()
    }).eq('id', card.id);

    // Insert review event
    await sb.from('flashcard_reviews').insert([{
      flashcard_id: card.id,
      rating,
      ease_factor_before: card.ease_factor || 2.5,
      ease_factor_after: sm2.ease_factor,
      interval_before: card.interval_days || 0,
      interval_after: sm2.interval_days,
      review_time_ms: timeSpentMs
    }]);
  } catch (e) {
    console.error('Failed to log review:', e);
  }

  currentStudyIndex++;
  renderCurrentStudyCard();
}

