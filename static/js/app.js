async function finalizeTestSubmission() {
  if (examTimerInterval) clearInterval(examTimerInterval);
  const sb = getSupabase();
  if (!sb || !currentExamAttempt) return;

  let correctCount = 0;
  let incorrectCount = 0;
  let unansweredCount = 0;

  const mistakesToInsert = [];
  const responsesToInsert = [];

  currentExamQuestions.forEach(q => {
    const isCorrect = q.user_answer && (q.user_answer.trim().toUpperCase() === q.correct_answer.trim().toUpperCase());
    if (!q.user_answer) {
      unansweredCount++;
    } else if (isCorrect) {
      correctCount++;
    } else {
      incorrectCount++;
      // Auto-log to mistakes
      mistakesToInsert.push({
        question_id: q.id,
        attempt_id: currentExamAttempt.attempt_id,
        subject_id: q.subject_id,
        chapter_id: q.chapter_id,
        user_selected_answer: q.user_answer,
        correct_answer: q.correct_answer,
        explanation: q.explanation || '',
        error_type: 'Unclassified',
        status: 'unresolved'
      });
    }

    responsesToInsert.push({
      attempt_id: currentExamAttempt.attempt_id,
      question_id: q.id,
      user_answer: q.user_answer,
      is_correct: isCorrect ? 1 : 0
    });
  });

  // SSC scoring: +2 for correct, -0.5 for wrong
  const score = Math.max(0, Math.round(((correctCount * 2) - (incorrectCount * 0.5)) * 100) / 100);
  const totalAttempted = correctCount + incorrectCount;
  const accuracy = totalAttempted > 0 ? Math.round((correctCount / totalAttempted) * 100) : 0;

  try {
    // Save attempt
    await sb.from('test_attempts').update({
      score,
      correct_count: correctCount,
      incorrect_count: incorrectCount,
      unanswered_count: unansweredCount,
      accuracy,
      time_taken_seconds: examTimeElapsedSeconds,
      status: 'completed',
      completed_at: new Date().toISOString()
    }).eq('id', currentExamAttempt.attempt_id);

    // Save responses
    if (responsesToInsert.length > 0) {
      await sb.from('test_responses').insert(responsesToInsert);
    }

    // Auto-save mistakes
    if (mistakesToInsert.length > 0) {
      await sb.from('mistakes').insert(mistakesToInsert);
    }
  } catch (e) {
    console.error('Failed to save test responses:', e);
  }

  closeModal('modal-exam-simulator');
  await viewTestResults(currentExamAttempt.attempt_id);
  await refreshGlobalBadges();
  loadTestsHistory();
}

